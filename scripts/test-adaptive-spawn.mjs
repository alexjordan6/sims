import assert from 'node:assert/strict';
import { AdaptiveSpawner } from '../games/village/adaptive-spawn.ts';
const p = { adaptiveSpawns:true, adaptiveHp:50, adaptiveEvery:8, adaptiveStart:1, adaptiveGrowth:0.25, adaptiveBatchCap:20, adaptiveAliveCap:100 };
const s = new AdaptiveSpawner(), batches=[];
const spawn = n => { batches.push(n); return n; };
const tick = (dt=8,hp=60,active=true,alive=0) => s.tick(dt,hp,active,alive,p,spawn);
tick(80,50); tick(80,49);
assert.equal(batches.length,0,'50 HP and below never spawn');
tick(7); assert.equal(batches.length,0);
tick(1); assert.deepEqual(batches,[1],'first batch waits full interval');
for(let i=0;i<7;i++) tick();
assert.deepEqual(batches,[1,1,1,1,2,2,2,2],'fractional growth accumulates');
tick(7); tick(50,40); tick(7);
assert.equal(batches.length,8,'low HP clears countdown and does not accumulate backlog');
tick(1); assert.equal(batches.at(-1),3,'recovery keeps ramp and waits a fresh interval');
tick(1000);
assert.equal(batches.length,10,'long frame produces one batch, never a catch-up burst');
tick(100,60,false);
assert.equal(batches.length,10,'inactive/sheltered player does not spawn');
tick(100,60,true,100);
assert.equal(batches.length,10,'living cap pauses spawning');
tick(8,60,true,99);
assert.equal(batches.at(-1),1,'partial batch respects remaining capacity');
const before=s.batches;
s.tick(8,60,true,0,p,()=>0);
assert.equal(s.batches,before,'failed placement does not increase difficulty');
p.adaptiveBatchCap=2; tick();
assert.equal(batches.at(-1),2,'batch cap applies live');
p.adaptiveHp=70; tick(); assert.equal(s.elapsed,0,'threshold changes apply live');
p.adaptiveHp=50; p.adaptiveEvery=1; tick(1);
assert.equal(batches.at(-1),2,'interval changes apply live');
p.adaptiveSpawns=false; tick();
assert.equal(s.batches,0); assert.equal(s.elapsed,0);
p.adaptiveSpawns=true; p.adaptiveGrowth=0; p.adaptiveStart=2;
tick(1); tick(1);
assert.deepEqual(batches.slice(-2),[2,2],'zero growth gives fixed batches');
s.reset(); assert.equal(s.batches,0); assert.equal(s.lastSpawned,0);
console.log('Adaptive spawning checks passed: threshold, timing, growth, recovery, pause, caps, failed placement, live tuning and reset.');
